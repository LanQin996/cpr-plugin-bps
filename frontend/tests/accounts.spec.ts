test('a single host account can be selected and cleared without logout', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '选择分组和账号', exact: true }).click()
  await expect(page.getByText('宿主已有账号', { exact: true })).toBeVisible()
  await page.getByRole('checkbox', { name: '宿主已有账号', exact: true }).locator('..').click()
  await page.waitForTimeout(350)
  await page.screenshot({ path: 'test-results/reuse-host.png', fullPage: true })
  await page.getByRole('button', { name: '应用选择（1）', exact: true }).click()
  await expect(page.getByText('复用宿主登录', { exact: true })).toBeVisible()
  await expect(page.getByRole('textbox', { name: '设备码', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '退出登录', exact: true })).toHaveCount(0)
  await page.screenshot({ path: 'test-results/host-connected.png', fullPage: true })
  await page.getByRole('button', { name: '选择分组和账号', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: '宿主已有账号', exact: true })).toBeChecked()
  await page.getByRole('button', { name: '清空选择', exact: true }).click()
  await page.getByRole('button', { name: '应用选择（0）', exact: true }).click()
  await page.getByRole('button', { name: '选择分组和账号', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: '宿主已有账号', exact: true })).toBeEnabled()
})

test('multiple groups and individual accounts stay independent and combine by union', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '选择分组和账号', exact: true }).click()
  await page.getByRole('checkbox', { name: '分组 A', exact: true }).locator('..').click()
  await page.getByRole('checkbox', { name: 'B1 账号', exact: true }).locator('..').click()
  await expect(page.getByText('最终生效 3 个账号', { exact: true })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'B1 账号', exact: true })).toBeEnabled()
  await expect(page.getByRole('checkbox', { name: '分组 B', exact: true })).not.toBeChecked()
  await page.getByRole('checkbox', { name: '分组 B', exact: true }).locator('..').click()
  await expect(page.getByText('最终生效 4 个账号', { exact: true })).toBeVisible()
  await page.getByRole('checkbox', { name: '分组 B', exact: true }).locator('..').click()
  await expect(page.getByRole('checkbox', { name: 'B1 账号', exact: true })).toBeChecked()
  await expect(page.getByText('最终生效 3 个账号', { exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/group-account-union.png', fullPage: true })
  await page.getByRole('button', { name: '应用选择（3）', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'B1 账号', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'B2 账号', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '选择分组和账号', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: '分组 A', exact: true })).toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'B1 账号', exact: true })).toBeChecked()
  await page.getByRole('checkbox', { name: '分组 A', exact: true }).locator('..').click()
  await expect(page.getByText('最终生效 1 个账号', { exact: true })).toBeVisible()
})
