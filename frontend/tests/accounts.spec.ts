import { expect, test } from '@playwright/test'

test('empty installation starts device authorization without account IDs or JSON', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('模拟预览，不会登录真实账号或修改宿主')).toBeVisible()
  await page.screenshot({ path: 'test-results/empty.png', fullPage: true })
  await page.getByRole('button', { name: '也可以使用独立 BPS 授权或导入文件', exact: true }).click()
  await page.getByRole('textbox', { name: '账号名称', exact: true }).fill('测试账号')
  await page.getByRole('button', { name: '获取设备码', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '设备码', exact: true })).toHaveValue('DEMO-2486')
  await page.screenshot({ path: 'test-results/device-login.png', fullPage: true })
  await expect(page.getByRole('heading', { name: '测试账号', exact: true })).toBeVisible({ timeout: 10000 })
  await expect(page.getByText('账号已授权并自动接入', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await expect(page.getByText('未登录', { exact: true })).toBeVisible()
})

test('OAuth file import and model editing use the page controls', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '也可以使用独立 BPS 授权或导入文件', exact: true }).click()
  await page.getByRole('textbox', { name: '账号名称', exact: true }).fill('导入账号')
  await page.getByRole('button', { name: '导入文件', exact: true }).click()
  await page.locator('#oauth-file').setInputFiles({ name: 'oauth.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ access_token: 'preview-only-value' })) })
  await page.getByRole('button', { name: '导入并接入', exact: true }).click()
  await expect(page.getByRole('heading', { name: '导入账号', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '模型设置', exact: true }).click()
  await page.getByRole('textbox', { name: '模型 ID，每行一个', exact: true }).fill('custom-authorized-model')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByText('custom-authorized-model', { exact: true })).toBeVisible()
  await expect(page.getByText('preview-only-value')).toHaveCount(0)
})

